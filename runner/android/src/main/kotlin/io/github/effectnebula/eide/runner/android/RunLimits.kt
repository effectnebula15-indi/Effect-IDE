package io.github.effectnebula.eide.runner.android

/**
 * Ограничения на запуск программы пользователя.
 *
 * Реализованы наблюдением снаружи, а не `setrlimit` внутри раннера. Причина
 * прагматичная: лимит на адресное пространство ставится в процессе, где уже
 * поднят ART, и рискует убить сам рантайм раньше пользовательского кода —
 * это записано как слабость в ADR-002. Наблюдение снаружи такой ошибки не имеет
 * и работает одинаково для любого будущего бэкенда.
 *
 * Цена честная: реакция не мгновенная (интервал опроса) и мы видим RSS всего
 * процесса, а не только объектов Python.
 */
data class RunLimits(
    /** Предел времени работы. `null` — не ограничивать. */
    val timeoutMillis: Long? = 30_000,
    /** Предел резидентной памяти процесса раннера. `null` — не ограничивать. */
    val maxResidentBytes: Long? = 512L * 1024 * 1024,
    /** Как часто проверять. Чаще — быстрее реакция и больше расход на опрос. */
    val pollIntervalMillis: Long = 250,
) {
    companion object {
        /** Без ограничений — для отладки самого механизма. */
        val NONE: RunLimits = RunLimits(timeoutMillis = null, maxResidentBytes = null)
    }
}

/** Почему программа была остановлена не по своей воле. */
enum class KillReason {
    /** Пользователь нажал «стоп». */
    ByUser,
    /** Превышен предел времени. */
    Timeout,
    /** Превышен предел памяти. */
    Memory,
}
