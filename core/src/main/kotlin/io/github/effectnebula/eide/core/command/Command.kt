package io.github.effectnebula.eide.core.command

/**
 * Команда палитры.
 *
 * Ни действия, ни горячей клавиши здесь нет — только то, что показывается и по
 * чему ищут. Действие живёт в точке сборки: `:core` не знает ни про окна, ни
 * про процессы, а команда «Запустить» — это ровно они. Связь по [id].
 *
 * [hint] — подпись справа: горячая клавиша или уточнение. В поиске не
 * участвует: иначе запрос «ctrl» выдавал бы половину списка.
 */
data class Command(
    val id: String,
    val title: String,
    val hint: String? = null,
)

/** Команда, подошедшая под запрос: с оценкой и позициями совпавших букв. */
data class CommandMatch(
    val command: Command,
    val score: Int,
    /** Индексы букв заголовка, попавших в запрос. Для подсветки в списке. */
    val positions: List<Int>,
)
