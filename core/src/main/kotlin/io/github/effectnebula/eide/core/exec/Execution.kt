package io.github.effectnebula.eide.core.exec

import java.io.File

/**
 * Ограничения на запуск программы пользователя.
 *
 * Реализуются наблюдением снаружи, а не `setrlimit` внутри процесса. Причина
 * прагматичная: лимит на адресное пространство ставится там, где уже поднят
 * рантайм, и рискует убить его раньше пользовательского кода — это записано
 * как слабость в ADR-002. Наблюдение снаружи такой ошибки не имеет и работает
 * одинаково для любого бэкенда.
 *
 * Цена честная: реакция не мгновенная (интервал опроса), и видно RSS всего
 * процесса, а не только объектов языка.
 */
data class RunLimits(
    /** Предел времени работы. `null` — не ограничивать. */
    val timeoutMillis: Long? = 30_000,
    /** Предел резидентной памяти процесса. `null` — не ограничивать. */
    val maxResidentBytes: Long? = 512L * 1024 * 1024,
    /** Как часто проверять. Чаще — быстрее реакция и больше расход на опрос. */
    val pollIntervalMillis: Long = 250,
) {
    companion object {
        /** Без ограничений — для отладки самого механизма. */
        val NONE: RunLimits = RunLimits(timeoutMillis = null, maxResidentBytes = null)
    }
}

/** Почему программа была остановлена не по своей воле. */
enum class KillReason {
    /** Пользователь нажал «стоп». */
    ByUser,

    /** Превышен предел времени. */
    Timeout,

    /** Превышен предел памяти. */
    Memory,
}

/**
 * Что запускаем.
 *
 * Параметры среды передаются картой, а не отдельными полями. Так через один и
 * тот же путь проходит и графика (`EIDE_CANVAS_*`), и всё, что появится
 * потом: бэкенду не нужно знать, что означают эти переменные.
 */
data class RunSpec(
    val script: File,
    val workDir: File,
    val limits: RunLimits = RunLimits(),
    val environment: Map<String, String> = emptyMap(),
)

/**
 * Что происходит с запущенной программой.
 *
 * Вызовы приходят из фоновых потоков бэкенда. Перекладывать их в поток
 * интерфейса — забота того, кто подписывается: ядро про потоки интерфейса
 * ничего не знает.
 */
interface RunListener {
    fun onStarted(pid: Int)
    fun onStdout(chunk: String)
    fun onStderr(chunk: String)

    /** Программа завершилась сама. */
    fun onExit(code: Int)

    /** Программу остановили: пользователь или сторож лимитов. */
    fun onKilled(reason: KillReason)

    /** Сломался сам механизм запуска, а не программа. */
    fun onFailure(error: Throwable)
}

/** Ручка запущенной программы. */
interface RunHandle {
    /**
     * Останавливает программу.
     *
     * Именно убийство процесса, а не просьба завершиться: программа в
     * `while True` ничего не читает, а прервать её изнутри интерпретатора
     * надёжно нельзя (ADR-002).
     */
    fun stop()
}

/**
 * Способ исполнить код пользователя.
 *
 * Одна абстракция на все реализации: встроенный интерпретатор на Android,
 * дочерний процесс на десктопе, дальше — WASM и удалённый сервер. Разница
 * между ними не должна протекать в интерфейс.
 */
interface ExecutionBackend {
    fun run(spec: RunSpec, listener: RunListener): RunHandle
}
