package io.github.effectnebula.eide.platform

/**
 * Границы графем — того, что пользователь считает одним символом.
 *
 * Курсор обязан двигаться по графемам, а не по code unit'ам: одна эмодзи с модификатором
 * цвета кожи — это до семи UTF-16 единиц, и стрелка вправо должна перепрыгнуть её целиком.
 *
 * Реализация платформенная (ADR-005): на Android есть ICU в составе системы, на Desktop
 * приходится брать своё. Работаем на уровне строки, а не всего документа — строка и так
 * уже нужна для отрисовки, а гонять по дереву весь текст ради одного шага курсора незачем.
 */
interface GraphemeBreaker {
    /** Офсет начала следующей графемы после [from], либо длина строки, если её нет. */
    fun next(line: CharSequence, from: Int): Int

    /** Офсет начала предыдущей графемы перед [from], либо 0. */
    fun previous(line: CharSequence, from: Int): Int
}
