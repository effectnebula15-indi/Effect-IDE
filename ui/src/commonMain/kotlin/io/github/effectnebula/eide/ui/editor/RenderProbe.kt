package io.github.effectnebula.eide.ui.editor

/**
 * Наблюдение за отрисовкой редактора — только для замеров (прототип P2).
 *
 * Раньше стенд замеров рисовал текст своим кодом, отдельным от редактора. Кода
 * там было меньше — ни гаттера, ни курсоров, ни подсветки, — и он отстал от
 * настоящего рендера, как только тот стал сложнее. Мерить не то, на чём стоит
 * решение по ADR-001, хуже, чем не мерить вовсе, поэтому второй рендерер удалён,
 * а стенд гоняет [CodeEditor] — со всем, что редактор рисует на самом деле.
 *
 * Цена решения названа прямо: в редакторе появился параметр, которого его логика
 * не требует. Он ничего не делает, пока равен null, и это единственное, что
 * защищает от его расползания.
 */
class RenderProbe(
    /**
     * Скорость автопрокрутки в пикселях в секунду. Ноль — прокрутка только пальцем.
     *
     * Нужна для измерений: результат, зависящий от того, как рукой водили по
     * экрану, невозможно сравнить с предыдущим.
     */
    val autoScrollPxPerSecond: Float = 0f,
) {
    /**
     * Счётчики кэша разметки на последнем нарисованном кадре.
     *
     * Обычные поля, а не состояние Compose, намеренно: пишутся они в фазе
     * отрисовки, а читаются в composable рядом. Будь это состояние, каждый кадр
     * вызывал бы пересборку стенда — и замер включал бы в себя стоимость
     * собственного отображения.
     */
    var cacheHits: Int = 0
        internal set
    var cacheMisses: Int = 0
        internal set
    var firstVisibleLine: Int = 0
        internal set
}
